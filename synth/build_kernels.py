#!/usr/bin/env python3
"""Generate the single-file Kaggle kernels from synth/ (Kaggle pushes one code file per kernel).

    python synth/build_kernels.py          # rewrite kernels/gemma4-synth-{factory,validate}/*.py
    python synth/build_kernels.py --check  # exit 1 if a generated kernel is stale

Each kernel = CONFIG block (edit it in the generated file or pass via synth/kernel_configs.json) + bootstrap that
unpacks the embedded synth package and the grader-image emulation (kernels/gemma4-lb-eval/gemma4-lb-eval.py,
imported as `gemma4_lb_eval`) and calls synth.<module>.main(CONFIG).
"""
import argparse
import base64
import hashlib
import json
import pprint
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
FILES = ["__init__.py", "common.py", "factory.py", "filter.py", "mutators.py", "patches.py", "repos.py",
         "statements.py", "synth_plug.py", "validate.py"]
LB = REPO / "kernels" / "gemma4-lb-eval" / "gemma4-lb-eval.py"
KERNELS = {
    "factory": ("gemma4-synth-factory", "factory", "Synthetic SWE task factory (CPU, internet on): clone, baseline, "
                "mutate, screen, package candidates. See synth/README.md."),
    "validate": ("gemma4-synth-validate", "validate", "Validate synthetic tasks with swegemma verify_task in the "
                 "grader-image emulation (CPU, internet off); write the dataset folder. See synth/README.md."),
}
CONFIGS = json.loads((HERE / "kernel_configs.json").read_text()) if (HERE / "kernel_configs.json").exists() else {}

BOOT = '''
import base64, os, sys, traceback, zlib
from pathlib import Path


def _scratch():
    for c in ("/root/synth", "/kaggle/synthscratch"):
        try:
            Path(c).mkdir(parents=True, exist_ok=True)
            return c
        except OSError:
            pass
    raise SystemExit("no writable scratch dir")


os.environ.setdefault("SYNTH_SCRATCH", _scratch())
PKG = Path(os.environ["SYNTH_SCRATCH"]).parent / "synth_pkg"
for _name, _blob in EMBED.items():
    _p = PKG / _name
    _p.parent.mkdir(parents=True, exist_ok=True)
    _p.write_bytes(zlib.decompress(base64.b64decode(_blob)))
sys.path.insert(0, str(PKG))

if __name__ == "__main__":
    from synth import {module} as _m
    from synth.common import log
    try:
        _m.main(CONFIG)
    except BaseException:
        log("CRASH: " + traceback.format_exc()[-4000:])
'''


def render(kind):
    name, module, doc = KERNELS[kind]
    blobs = {f"synth/{f}": (HERE / f).read_bytes() for f in FILES}
    blobs["gemma4_lb_eval.py"] = LB.read_bytes()
    sha = hashlib.sha256(b"".join(k.encode() + v for k, v in sorted(blobs.items()))).hexdigest()[:16]
    lines = [f'"""Kaggle CPU kernel {name} (GENERATED by synth/build_kernels.py, do not edit; sources sha {sha}).\n\n'
             f'{doc}\n"""\n', f"CONFIG = {pprint.pformat(CONFIGS.get(kind, {}), width=110)}\n\n", "EMBED = {\n"]
    for k, v in sorted(blobs.items()):
        lines.append(f"    {k!r}: {base64.b64encode(zlib.compress(v, 9)).decode()!r},\n")
    lines.append("}\n")
    lines.append(BOOT.replace("{module}", module))
    return name, "".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = False
    for kind in KERNELS:
        name, text = render(kind)
        path = REPO / "kernels" / name / f"{name}.py"
        if a.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {path}")
                stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
            print(f"wrote {path} ({len(text) / 1e3:.0f} kB)")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
